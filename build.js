#!/usr/bin/env node
// Generates the per-language pages and SEO files from the English source.
//
//   node build.js
//
// Source of truth: index.html (English text) + js/translations.js.
// Output: SEO <head> block in index.html, de/index.html, hu/index.html,
//         ro/index.html and sitemap.xml. Run it after every text change,
//         before committing / deploying. Never edit the generated pages by hand.

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const SITE_URL = 'https://szilardtoth94.github.io/language-teacher/';
const LANGS = ['en', 'de', 'hu', 'ro'];
const DEFAULT_LANG = 'en'; // served at the site root

const root = __dirname;
const translations = vm.runInNewContext(
  fs.readFileSync(path.join(root, 'js/translations.js'), 'utf8') + ';translations'
);

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const escAttr = (s) => esc(s).replace(/"/g, '&quot;');
const langDir = (l) => (l === DEFAULT_LANG ? '' : `${l}/`);
const pageUrl = (l) => SITE_URL + langDir(l);

function seoBlock(lang) {
  const t = translations[lang];
  const url = pageUrl(lang);
  const img = SITE_URL + 'img/og-image.jpg';
  const alternates = LANGS.map((l) => `  <link rel="alternate" hreflang="${l}" href="${pageUrl(l)}" />`)
    .concat(`  <link rel="alternate" hreflang="x-default" href="${pageUrl(DEFAULT_LANG)}" />`);
  const otherLocales = LANGS.filter((l) => l !== lang)
    .map((l) => `  <meta property="og:locale:alternate" content="${translations[l]['meta.locale']}" />`);

  const jsonLd = {
    '@context': 'https://schema.org',
    '@type': 'EducationalOrganization',
    name: 'German Go Online',
    url,
    logo: SITE_URL + 'img/icon-512.png',
    image: img,
    description: t['meta.description'],
    email: 'GlobalTalk@mail.com',
    telephone: '+40747552607',
    sameAs: ['https://www.instagram.com/germango_online/'],
    knowsLanguage: 'de',
    availableLanguage: LANGS,
    founder: {
      '@type': 'Person',
      name: 'Szaniszló Boglárka',
      image: SITE_URL + 'img/profile.jpeg',
      knowsLanguage: LANGS,
    },
  };

  return [
    '  <!-- seo:start (generated by build.js — do not edit) -->',
    `  <title>${esc(t['meta.title'])}</title>`,
    `  <meta name="description" content="${escAttr(t['meta.description'])}" />`,
    `  <link rel="canonical" href="${url}" />`,
    ...alternates,
    '  <meta property="og:type" content="website" />',
    '  <meta property="og:site_name" content="German Go Online" />',
    `  <meta property="og:locale" content="${t['meta.locale']}" />`,
    ...otherLocales,
    `  <meta property="og:title" content="${escAttr(t['meta.title'])}" />`,
    `  <meta property="og:description" content="${escAttr(t['meta.description'])}" />`,
    `  <meta property="og:url" content="${url}" />`,
    `  <meta property="og:image" content="${img}" />`,
    '  <meta property="og:image:width" content="1200" />',
    '  <meta property="og:image:height" content="630" />',
    '  <meta property="og:image:alt" content="German Go Online logo — glowing globe" />',
    '  <meta name="twitter:card" content="summary_large_image" />',
    `  <meta name="twitter:title" content="${escAttr(t['meta.title'])}" />`,
    `  <meta name="twitter:description" content="${escAttr(t['meta.description'])}" />`,
    `  <meta name="twitter:image" content="${img}" />`,
    '  <script type="application/ld+json">',
    '  ' + JSON.stringify(jsonLd),
    '  </script>',
    '  <!-- seo:end -->',
  ].join('\n');
}

const SEO_RE = /  <!-- seo:start[\s\S]*?<!-- seo:end -->/;

function render(source, lang) {
  const t = translations[lang];
  let html = source.replace(SEO_RE, () => seoBlock(lang));
  html = html.replace(/<html lang="[^"]*">/, `<html lang="${lang}">`);
  if (lang === DEFAULT_LANG) return html;

  const missing = new Set();
  const get = (key) => {
    if (t[key] === undefined) missing.add(key);
    return t[key];
  };

  // Element text (plain) and inner HTML
  html = html.replace(
    /(<(\w+)\b[^>]*?\sdata-i18n(-html|-option)?="([^"]+)"[^>]*>)([\s\S]*?)(<\/\2>)/g,
    (m, open, tag, kind, key, inner, close) => {
      const v = get(key);
      if (v === undefined) return m;
      return open + (kind === '-html' ? v : esc(v)) + close;
    }
  );
  // Attributes
  html = html.replace(/(\sdata-i18n-placeholder="([^"]+)"[^>]*?\splaceholder=")[^"]*"/g,
    (m, pre, key) => (get(key) === undefined ? m : pre + escAttr(get(key)) + '"'));
  html = html.replace(/(<a\b[^>]*?\shref=")[^"]*("[^>]*?\sdata-i18n-href="([^"]+)")/g,
    (m, pre, post, key) => (get(key) === undefined ? m : pre + escAttr(get(key)) + post));

  // Relative asset/page paths: pages live one folder deeper
  html = html.replace(/(\s(?:src|href)=")(?![a-z]+:|#|\/|\.\.\/)([^"]*)"/gi, (m, pre, p) => {
    if (p === './' ) return `${pre}../"`;
    return `${pre}../${p}"`;
  });
  // The language links point at sibling folders
  html = html.replace(/href="\.\.\/(de|hu|ro)\/"/g, (m, l) => (l === lang ? 'href="./"' : m));
  html = html.replace(/(<a class="lang-btn)( active)?(" data-lang="([a-z]+)")/g,
    (m, a, _active, rest, l) => a + (l === lang ? ' active' : '') + rest);

  if (missing.size) throw new Error(`[${lang}] missing translations: ${[...missing].join(', ')}`);
  return html;
}

const sourcePath = path.join(root, 'index.html');
const source = fs.readFileSync(sourcePath, 'utf8');
if (!SEO_RE.test(source)) throw new Error('index.html is missing the <!-- seo:start --> … <!-- seo:end --> markers');

for (const lang of LANGS) {
  const out = render(source, lang);
  const file = path.join(root, langDir(lang), 'index.html');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, out);
  console.log('wrote', path.relative(root, file));
}

const today = new Date().toISOString().slice(0, 10);
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${LANGS.map((l) => `  <url>
    <loc>${pageUrl(l)}</loc>
    <lastmod>${today}</lastmod>
${LANGS.map((a) => `    <xhtml:link rel="alternate" hreflang="${a}" href="${pageUrl(a)}" />`).join('\n')}
    <xhtml:link rel="alternate" hreflang="x-default" href="${pageUrl(DEFAULT_LANG)}" />
  </url>`).join('\n')}
</urlset>
`;
fs.writeFileSync(path.join(root, 'sitemap.xml'), sitemap);
console.log('wrote sitemap.xml');
